"""Builds FINAL-API-ENDPOINT-INVENTORY.md from an exported OpenAPI document and a static scan of the live smoke scripts.

Usage: python3 endpoint_inventory.py <openapi.json> <out.md> <smoke_script.py>...
Verification column: LIVE_VERIFIED when a smoke script issues that METHOD against that path template (string literal or
a variable assigned from a literal in the same script); "not in live journeys" otherwise. The scan is static: a call
built by other means is reported as not found (conservative).
"""
import json
import re
import sys

METHODS = ("get", "post", "put", "patch", "delete")


def norm(path):
    path = path.split("?", 1)[0].rstrip("/")
    return re.sub(r"\{[^}]*\}", "*", path)


def scan(scripts):
    calls = set()
    for script in scripts:
        text = open(script, encoding="utf-8").read()
        variables = {m.group(1): m.group(2) for m in re.finditer(r'^\s*(\w+)\s*=\s*f?"(/api/[^"]*)"', text, re.M)}
        for m in re.finditer(r'call\(\s*"(GET|POST|PUT|PATCH|DELETE)"\s*,\s*(f?"(/[^"]*)"|(\w+)(?:\s*\+\s*f?"([^"]*)")?)', text):
            method = m.group(1)
            if m.group(3):
                path = m.group(3)
            elif m.group(4) in variables:
                path = variables[m.group(4)] + (m.group(5) or "")
            else:
                continue
            calls.add((method, norm(path)))
    return calls


def main(src, out, scripts):
    doc = json.load(open(src, encoding="utf-8"))
    calls = scan(scripts)
    rows, live = [], 0
    for path, item in sorted(doc["paths"].items()):
        for method in METHODS:
            op = item.get(method)
            if op is None:
                continue
            tag = (op.get("tags") or ["-"])[0]
            secured = "bearer" if op.get("security", doc.get("security")) else "anonymous"
            body = "declared" if op.get("requestBody", {}).get("content") else "none declared"
            verified = (method.upper(), norm(path)) in calls
            live += verified
            rows.append(f"| {method.upper()} | `{path}` | {tag} | {secured} | {body} | IMPLEMENTED | "
                        f"{'LIVE_VERIFIED' if verified else 'not in live journeys'} |")
    head = [
        "# Final API endpoint inventory",
        "",
        f"Generated by `tools/captain/endpoint_inventory.py` from the OpenAPI document exported from the running Development API "
        f"(`{src.rsplit('/', 1)[-1]}`) and a static scan of: {', '.join('`' + s.rsplit('/', 1)[-1] + '`' for s in scripts)}.",
        "",
        f"**{len(rows)} operations / {len(doc['paths'])} paths; {live} LIVE_VERIFIED by the live smoke scripts.** "
        "Every listed operation is mapped and reachable (IMPLEMENTED). Excluded scope (cost, BOQ, 3D, payments) has no endpoints.",
        "",
        "- `security` is taken from the OpenAPI document. Authorization (owner scoping, role and privilege checks) is enforced "
        "server-side and verified in the journeys and unit tests; it is not visible in OpenAPI.",
        "- `body`: `declared` = JSON request schema present in OpenAPI; `none declared` = OpenAPI declares no request body "
        "(several minimal-API routes read a JSON body manually, so this does not mean the route takes no body; see the "
        "frontend integration guides for those shapes).",
        "- `not in live journeys` does not mean untested: many of these are covered by unit/contract tests (see "
        "FINAL-LIVE-INTEGRATION-EVIDENCE); it means no live smoke script calls them.",
        "",
        "| Method | Path | Tag | Security | Body | Status | Verification |",
        "|---|---|---|---|---|---|---|",
    ]
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(head + rows) + "\n")
    print(f"operations={len(rows)} live_verified={live}")


if __name__ == "__main__":
    if len(sys.argv) < 4:
        sys.exit("usage: endpoint_inventory.py <openapi.json> <out.md> <smoke_script.py>...")
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
